"""
Sandboxed code runner.

Executes candidate Python code + test suite in an isolated subprocess
with a hard timeout.  Captures stdout, stderr, return code, and
duration.  Parses pytest / unittest style output to count passed and
failed tests.

Security note
-------------
This runner uses subprocess with a timeout.  It does NOT provide
OS-level sandboxing (cgroups, seccomp, containers).  For production
deployments, wrap this in a Docker container or use a service like
E2B / Modal.
"""

from __future__ import annotations

import re
import subprocess
import sys
import tempfile
import time
from pathlib import Path

from app.core.logger import logger
from app.core.schemas import ExecutionResult, ExecutionStatus


def _count_tests(output: str) -> tuple[int, int]:
    """
    Parse test output to extract (passed, total).

    Supports patterns like:
      - "Ran 5 tests"  (unittest)
      - "5 passed, 2 failed"  (pytest)
      - Simple assert-based: counts "AssertionError" occurrences
    """
    passed = 0
    failed = 0

    # pytest style: "5 passed" / "2 failed"
    m_passed = re.search(r"(\d+)\s+passed", output)
    m_failed = re.search(r"(\d+)\s+failed", output)
    if m_passed:
        passed = int(m_passed.group(1))
    if m_failed:
        failed = int(m_failed.group(1))
    if m_passed or m_failed:
        return passed, passed + failed

    # unittest style: "Ran N tests"
    m_ran = re.search(r"Ran\s+(\d+)\s+test", output)
    if m_ran:
        total = int(m_ran.group(1))
        if "OK" in output:
            return total, total
        m_unit_fail = re.search(r"failures=(\d+)", output)
        unit_fails = int(m_unit_fail.group(1)) if m_unit_fail else 0
        m_unit_err = re.search(r"errors=(\d+)", output)
        unit_errs = int(m_unit_err.group(1)) if m_unit_err else 0
        return total - unit_fails - unit_errs, total

    # Fallback: count assertion errors in output
    assertion_errors = output.count("AssertionError")
    if assertion_errors > 0:
        total_asserts = output.count("assert ")
        return max(0, total_asserts - assertion_errors), max(total_asserts, assertion_errors)

    return 0, 0


def run_code_in_sandbox(
    implementation_code: str,
    test_code: str,
    timeout: int = 10,
) -> ExecutionResult:
    """
    Execute implementation_code followed by test_code in a fresh
    Python subprocess.

    Parameters
    ----------
    implementation_code : str
        The candidate solution generated by the Actor.
    test_code : str
        The test suite that validates the implementation.
    timeout : int
        Maximum wall-clock seconds before the process is killed.

    Returns
    -------
    ExecutionResult
        Structured result with status, outputs, and test counts.
    """
    combined = f"{implementation_code}\n\n{test_code}"

    with tempfile.NamedTemporaryFile(
        mode="w", suffix=".py", delete=False, encoding="utf-8"
    ) as tmp:
        tmp.write(combined)
        tmp_path = Path(tmp.name)

    start = time.perf_counter()
    try:
        result = subprocess.run(
            [sys.executable, str(tmp_path)],
            capture_output=True,
            text=True,
            timeout=timeout,
            cwd=tempfile.gettempdir(),
        )
        duration = time.perf_counter() - start
        full_output = result.stdout + result.stderr

        if result.returncode == 0:
            passed, total = _count_tests(full_output)
            if total == 0:
                passed, total = 1, 1
            return ExecutionResult(
                status=ExecutionStatus.SUCCESS,
                stdout=result.stdout,
                stderr=result.stderr,
                return_code=result.returncode,
                duration_seconds=round(duration, 3),
                tests_passed=passed,
                tests_total=total,
            )

        # Non-zero exit -- classify the error
        if "SyntaxError" in result.stderr:
            status = ExecutionStatus.SYNTAX_ERROR
        elif "AssertionError" in full_output or "FAILED" in full_output:
            status = ExecutionStatus.TEST_FAILURE
        else:
            status = ExecutionStatus.RUNTIME_ERROR

        passed, total = _count_tests(full_output)
        return ExecutionResult(
            status=status,
            stdout=result.stdout,
            stderr=result.stderr,
            return_code=result.returncode,
            duration_seconds=round(duration, 3),
            tests_passed=passed,
            tests_total=total,
        )

    except subprocess.TimeoutExpired:
        duration = time.perf_counter() - start
        logger.warning(f"Sandbox execution timed out after {timeout}s")
        return ExecutionResult(
            status=ExecutionStatus.TIMEOUT,
            stderr=f"Process killed after {timeout}s timeout",
            duration_seconds=round(duration, 3),
        )
    except Exception as exc:
        duration = time.perf_counter() - start
        logger.error(f"Sandbox execution failed: {exc}")
        return ExecutionResult(
            status=ExecutionStatus.RUNTIME_ERROR,
            stderr=str(exc),
            duration_seconds=round(duration, 3),
        )
    finally:
        try:
            tmp_path.unlink(missing_ok=True)
        except OSError:
            pass
